-- Память: автоматическая запись и удаление владельцем.
--
-- 04_MEMORY_AND_CONTINUITY §4 допускает auto-accept для малочувствительных и
-- явно сформулированных сведений. Непереговорное остаётся: запись видима,
-- объяснима и отменяема. Автоматическая запись — не скрытая запись, поэтому
-- у каждой записи хранится, кто и почему её принял.

-- auto_decision объясняет, почему кандидат был принят или вынесен на решение.
ALTER TABLE memory_candidates ADD COLUMN auto_decision TEXT NOT NULL DEFAULT '';

-- forgotten_at отмечает удаление содержания владельцем.
--
-- Физически удалить событие из журнала нельзя без нарушения целостности
-- (06_SECURITY §11), поэтому содержание в проекции затирается, а сама запись
-- остаётся надгробием: видно, что нечто было и было удалено.
ALTER TABLE memory_items ADD COLUMN forgotten_at TEXT;
